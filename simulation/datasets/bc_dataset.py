"""Demonstration dataset generation for behavior cloning.

Provenance
----------
The demonstrations are generated *by this project* with the deterministic expert
controller (`ik_planner_baseline`) driving the reach environment. They are not
third-party data, carry no external licence, and are fully reproducible from
seed + configuration. The dataset manifest records the generating policy, the
scenario suite hash, and the seed so every example is traceable to a real
episode.

This is a small, honest dataset: it exists to train and evaluate a compact
behavior-cloning policy, not to claim a large-scale imitation result.

Format
------
Each demonstration is a set of (observation features, expert action) pairs
captured at a fixed control stride. Features are the observation subset a policy
can use (joint positions/velocities and the end-effector-to-target vector);
labels are the expert's desired joint positions. Arrays are stored as a
compressed ``.npz`` plus a JSON manifest with a schema version and checksum.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import numpy as np

from simulation.environments.reach_env import ReachEnv
from simulation.environments.reach_task import DEFAULT_REACH_SPEC
from simulation.policies.registry import build_policy
from simulation.scenarios.generator import Scenario, ScenarioSuite

#: Feature layout for the behavior-cloning policy. Frozen so training and
#: inference cannot silently disagree.
FEATURE_NAMES: tuple[str, ...] = (
    "qpos_1",
    "qpos_2",
    "qpos_3",
    "qpos_4",
    "qvel_1",
    "qvel_2",
    "qvel_3",
    "qvel_4",
    "ee_target_x",
    "ee_target_y",
    "ee_target_z",
    "ee_target_dist",
)
LABEL_NAMES: tuple[str, ...] = ("qpos_1", "qpos_2", "qpos_3", "qpos_4")

DATASET_SCHEMA_VERSION = "1"


@dataclass
class DatasetManifest:
    schema_version: str
    expert_policy: str
    expert_version: str
    task_name: str
    task_version: str
    suite_name: str
    suite_version: str
    suite_hash: str
    split: str
    base_seed: int
    control_stride: int
    n_episodes: int
    n_samples: int
    feature_names: list[str]
    label_names: list[str]
    checksum_sha256: str
    provenance_note: str = (
        "Generated by SimEval from real MuJoCo rollouts of the deterministic "
        "expert controller. No third-party data."
    )
    extra: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def featurize(env: ReachEnv) -> np.ndarray:
    """Build the policy input vector from the live environment state."""
    qpos = env.joint_positions()
    qvel = env.joint_velocities()
    vec = env.target_position() - env.ee_position()
    dist = float(np.linalg.norm(vec))
    return np.concatenate([qpos, qvel, vec, np.array([dist])]).astype(np.float64)


def generate_dataset(
    suite: ScenarioSuite,
    *,
    split: str = "dev",
    expert_policy: str = "ik_planner_baseline",
    control_stride: int = 2,
    base_seed: int = 4242,
) -> dict[str, np.ndarray]:
    """Roll the expert over ``split`` scenarios and collect (features, labels).

    ``control_stride`` records every Nth control step to decorrelate adjacent
    samples; it does not change how the expert acts.
    """
    if control_stride < 1:
        raise ValueError("control_stride must be >= 1")

    scenarios: list[Scenario] = (
        suite.scenarios if split == "all" else suite.by_split(split)  # type: ignore[arg-type]
    )
    if not scenarios:
        raise ValueError(f"no scenarios in split {split!r}")

    features: list[np.ndarray] = []
    labels: list[np.ndarray] = []

    for sc in scenarios:
        env = ReachEnv(spec=DEFAULT_REACH_SPEC)
        try:
            env.set_target(np.asarray(sc.target_position, dtype=float))
            obs = env.reset(
                seed=sc.seed,
                initial_qpos=(
                    np.asarray(sc.initial_qpos, dtype=float)
                    if sc.initial_qpos is not None
                    else None
                ),
                qpos_noise=sc.qpos_noise,
            )
            expert = build_policy(expert_policy, None, env.kinematics_context())
            expert.reset()

            for step in range(DEFAULT_REACH_SPEC.max_steps):
                action = expert.act(obs)
                if step % control_stride == 0:
                    features.append(featurize(env))
                    labels.append(np.asarray(action, dtype=np.float64))
                result = env.step(action)
                obs = result.observation
                if result.terminated or result.truncated:
                    break
        finally:
            env.close()

    x = np.stack(features, axis=0)
    y = np.stack(labels, axis=0)
    return {"features": x, "labels": y}


def _checksum(arrays: dict[str, np.ndarray]) -> str:
    h = hashlib.sha256()
    for key in sorted(arrays):
        h.update(key.encode())
        h.update(np.ascontiguousarray(arrays[key]).tobytes())
    return h.hexdigest()


def _savez(path: Path, arrays: dict[str, np.ndarray]) -> None:
    # np.savez_compressed is untyped and its keyword-only bool collides with
    # mypy's expectations; call it through this small shim.
    np.savez_compressed(str(path), **arrays)  # type: ignore[arg-type]


def save_dataset(
    arrays: dict[str, np.ndarray],
    *,
    directory: str | Path,
    manifest: DatasetManifest,
) -> Path:
    """Persist arrays and a manifest, returning the manifest path."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    checksum = _checksum(arrays)
    manifest.checksum_sha256 = checksum
    manifest.n_samples = int(arrays["features"].shape[0])
    _savez(directory / "data.npz", arrays)
    manifest_path = directory / "manifest.json"
    manifest_path.write_text(json.dumps(manifest.to_dict(), indent=2, sort_keys=True), encoding="utf-8")
    return manifest_path


def load_dataset(directory: str | Path) -> tuple[dict[str, np.ndarray], DatasetManifest]:
    directory = Path(directory)
    manifest_raw = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
    manifest = DatasetManifest(**manifest_raw)
    with np.load(directory / "data.npz", allow_pickle=False) as data:
        arrays = {k: data[k] for k in data.files}
    if _checksum(arrays) != manifest.checksum_sha256:
        raise ValueError("dataset checksum mismatch; file may be corrupted")
    return arrays, manifest


